import assert from 'node:assert/strict';
import * as T from 'three';
import {lookDelta} from '../app/decorate/look-input.ts';
import {pickFurniture} from '../app/decorate/scene-picking.ts';
assert(lookDelta(new Set(['arrowleft']),.1).yaw>0);
assert(lookDelta(new Set(['arrowright']),.1).yaw<0);
assert(lookDelta(new Set(['arrowup']),.1).pitch>0);
assert(lookDelta(new Set(['arrowdown']),.1).pitch<0);
assert.deepEqual(lookDelta(new Set(['arrowleft','arrowright','arrowup','arrowdown']),.1),{yaw:0,pitch:0});
assert.deepEqual(lookDelta(new Set(),.1),{yaw:0,pitch:0},'released arrows stop turning');
const chair=new T.Group(),nested=new T.Group();nested.add(new T.Mesh(new T.BoxGeometry(1,1,1),new T.MeshBasicMaterial()));chair.add(nested);chair.position.z=-3;chair.updateMatrixWorld(true);
const wall=new T.Mesh(new T.BoxGeometry(2,2,.15),new T.MeshBasicMaterial());wall.position.z=-1;wall.updateMatrixWorld(true);
const ray=new T.Raycaster(new T.Vector3(),new T.Vector3(0,0,-1));
assert.equal(pickFurniture(ray,[chair],[]),chair,'nested furniture hover resolves its catalog group');
assert.equal(pickFurniture(ray,[chair],[wall]),null,'walls suppress hidden-object hints');
wall.visible=false;assert.equal(pickFurniture(ray,[chair],[wall]),chair,'hidden cutaway geometry does not block hints');wall.visible=true;
wall.position.x=4;wall.updateMatrixWorld(true);assert.equal(pickFurniture(ray,[chair],[wall]),chair);
ray.set(new T.Vector3(),new T.Vector3(1,0,0));assert.equal(pickFurniture(ray,[chair],[]),null,'empty space clears hover');
console.log('PASS: all four arrow directions, release/opposing keys, furniture hover, empty space, and wall occlusion.');
